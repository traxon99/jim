#!/usr/bin/env node
// Regenerates components/exercises/body-map-art.ts from MuscleMap's flat
// vector bodies (@musclemap/assets, MIT). The art is vendored, not a
// dependency, so upstream changes can't move a muscle under us.
//
//   curl -sSL https://registry.npmjs.org/@musclemap/assets/-/assets-1.1.0.tgz | tar xz -C /tmp/mm
//   node scripts/vendor-musclemap.mjs /tmp/mm/package
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const pkg = process.argv[2];
if (!pkg) throw new Error("usage: vendor-musclemap.mjs <path to @musclemap/assets package>");

// MuscleMap group → Jim's muscle vocabulary (packages/core MUSCLES).
const GROUPS = {
  TRAPEZIUS: "traps",
  CHEST: "chest",
  SHOULDERS_FRONT: "shoulders",
  SHOULDERS_SIDE: "shoulders",
  SHOULDERS_REAR: "shoulders",
  BICEPS: "biceps",
  TRICEPS: "triceps",
  FOREARMS: "forearms",
  CORE: "abdominals",
  OBLIQUES: "abdominals",
  ABDUCTORS: "abductors",
  ADDUCTORS: "adductors",
  QUADS: "quadriceps",
  CALVES: "calves",
  RHOMBOIDS: "middle back",
  LATS: "lats",
  BACK_LOWER: "lower back",
  GLUTES: "glutes",
  HAMSTRINGS: "hamstrings",
};

/** Whole-number coordinates: the box is 1024 wide, so a pixel is plenty. */
const round = (d) =>
  d
    .replace(/-?\d+(\.\d+)?/g, (n) => String(Math.round(Number(n))))
    .replace(/\s+/g, " ")
    .trim();

const meanX = (d) => {
  const n = d.match(/-?\d+(\.\d+)?/g).map(Number);
  let sum = 0;
  for (let i = 0; i < n.length - 1; i += 2) sum += n[i];
  return sum / Math.floor(n.length / 2);
};

async function figure(file, view) {
  const mod = await import(pathToFileURL(join(pkg, "dist", file)).href);
  const diagram = Object.values(mod)[0];
  const regions = diagram.muscles.map((m) => {
    const muscle = GROUPS[m.group];
    if (!muscle) throw new Error(`unmapped MuscleMap group ${m.group}`);
    // MuscleMap's _LEFT/_RIGHT ids mean the viewer's side in both views, so
    // the body's side comes from where the path sits: the viewer's left is
    // the person's right on the front, their left on the back.
    const viewerLeft = meanX(m.d) < diagram.centerX;
    const side = view === "front" ? (viewerLeft ? "right" : "left") : viewerLeft ? "left" : "right";
    return { muscle, surface: m.group, side, d: round(m.d) };
  });
  return {
    viewBox: diagram.viewBox,
    outline: diagram.outline.map((o) => round(o.d)),
    regions,
  };
}

const front = await figure("male-front.js", "front");
const back = await figure("male-back.js", "back");
const license = readFileSync(join(pkg, "LICENSE"), "utf8").split("\n---")[0].trim();

const out = `// Generated by scripts/vendor-musclemap.mjs from @musclemap/assets 1.1.0
// (https://github.com/Jsplice/MuscleMap), flat vector male front and back.
// Do not edit by hand; the neck shapes live in body-map.tsx.
//
${license
  .split("\n")
  .map((line) => `// ${line}`.trimEnd())
  .join("\n")}

import type { Muscle } from "@jim/core";

export interface ArtRegion {
  muscle: Muscle;
  /**
   * MuscleMap's own group (SHOULDERS_REAR, OBLIQUES…), finer than Jim's for
   * a few muscles, so Muscle detail (issue #876) can shade those apart.
   */
  surface: string;
  /** The body's own side, not the viewer's. */
  side: "left" | "right";
  d: string;
}

export interface ArtFigure {
  viewBox: string;
  outline: readonly string[];
  regions: readonly ArtRegion[];
}

export const FRONT_ART: ArtFigure = ${JSON.stringify(front, null, 2)};

export const BACK_ART: ArtFigure = ${JSON.stringify(back, null, 2)};
`;

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  "../components/exercises/body-map-art.ts",
);
writeFileSync(target, out);
console.log(`wrote ${target} (${out.length} bytes)`);
