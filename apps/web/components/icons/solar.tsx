import type { ComponentType, ReactNode, SVGProps } from "react";

/**
 * Every icon in the app is Solar by 480 Design, CC BY 4.0 (#800; tab bar
 * #788). Each export keeps the Lucide name it replaced, so call sites read the
 * same, and draws Solar's linear glyph. Inlined, not fetched, so icons work
 * offline. Generated from @iconify-json/solar; regenerate rather than
 * hand-edit a path.
 *
 * Props follow Lucide's: `strokeWidth` sets the line weight (Solar's own is
 * 1.5), `size` the width and height, and `fill` other than "none" switches an
 * icon that has one to its bold glyph (the filled home-gym star and Start buttons' play triangle).
 */
export type IconProps = Omit<SVGProps<SVGSVGElement>, "ref"> & {
  size?: number | string;
};

export type IconComponent = ComponentType<IconProps>;

function solar(name: string, line: ReactNode, bold?: ReactNode): IconComponent {
  function SolarIcon({ size = 24, strokeWidth = 1.5, fill, ...rest }: IconProps) {
    const filled = bold !== undefined && fill !== undefined && fill !== "none";
    const labelled = rest["aria-label"] !== undefined || rest["aria-labelledby"] !== undefined;
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        viewBox="0 0 24 24"
        width={size}
        height={size}
        fill="none"
        strokeWidth={strokeWidth}
        aria-hidden={labelled ? undefined : true}
        focusable="false"
        role={labelled ? "img" : undefined}
        {...rest}
      >
        {filled ? bold : line}
      </svg>
    );
  }
  SolarIcon.displayName = name;
  return SolarIcon;
}

